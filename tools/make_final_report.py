def code(text):
    return re.sub(r"`([^`]+)`", lambda m: f'<font face="Courier">{m.group(1)}</font>', text)


def p(text, style=BODY):
    return Paragraph(code(text), style)


def bullets(items, style=BUL):
    return [Paragraph(code(t), style, bulletText="-") for t in items]


def table(rows, widths, shade=None, bold_first_col=False):
    data = [[Paragraph(f'<font color="white"><b>{c}</b></font>', CELL) for c in rows[0]]]
    for r in rows[1:]:
        data.append([p(f"<b>{c}</b>" if (bold_first_col and i == 0) else str(c), CELL) for i, c in enumerate(r)])
    t = Table(data, colWidths=[w * mm for w in widths], repeatRows=1)
    st = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#A6A6A6")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
          ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3),
          ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
          ("BACKGROUND", (0, 0), (-1, 0), HEAD)]
    for r, c in (shade or {}).items():
        st.append(("BACKGROUND", (0, r), (-1, r), c))
    t.setStyle(TableStyle(st))
    return t


def chart(name, width_mm):
    path = CHARTS / name
    img = Image(str(path))
    ratio = img.imageHeight / img.imageWidth
    img.drawWidth = width_mm * mm
    img.drawHeight = width_mm * mm * ratio
    return img


